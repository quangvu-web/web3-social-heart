import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

function gitSha() {
  try {
    return execSync("git rev-parse --short=12 HEAD", { stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return null;
  }
}

const builtAt = new Date().toISOString();
const version = process.env.VITE_APP_VERSION || gitSha() || builtAt.replace(/[-:.TZ]/g, "").slice(0, 14);
const payload = { version, builtAt };

const publicPath = resolve("public/version.json");
const generatedPath = resolve("src/generated/appVersion.ts");

mkdirSync(dirname(publicPath), { recursive: true });
mkdirSync(dirname(generatedPath), { recursive: true });

writeFileSync(publicPath, `${JSON.stringify(payload, null, 2)}\n`);
writeFileSync(
  generatedPath,
  `// Generated by scripts/generate-version.mjs\nexport const APP_VERSION = ${JSON.stringify(version)};\nexport const APP_BUILT_AT = ${JSON.stringify(builtAt)};\n`,
);

console.log(`[version] ${version} built at ${builtAt}`);
