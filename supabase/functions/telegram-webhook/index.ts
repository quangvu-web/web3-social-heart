import {
  getTelegramClients,
  sendTelegramMessage,
  sha256Hex,
  telegramCorsHeaders,
  telegramJson,
} from "../_shared/telegram.ts";

type TgMessage = {
  message_id?: number;
  chat?: { id?: number; type?: string; title?: string };
  from?: { id?: number; username?: string; first_name?: string; is_bot?: boolean };
  text?: string;
};

type TelegramUpdate = {
  update_id?: number;
  message?: TgMessage;
  edited_message?: TgMessage;
};

function safeEqual(a: string | null, b: string): boolean {
  if (!a || a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

function isStartCommand(text: string): boolean {
  return /^\/start(@|\s|$)/i.test(text);
}

function getStartToken(text: string): string | null {
  const parts = text.trim().split(/\s+/);
  return parts.length > 1 ? parts[1] : null;
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: telegramCorsHeaders });
  if (req.method !== "POST") return telegramJson({ error: "Method not allowed" }, 405);

  const configuredSecret = Deno.env.get("TELEGRAM_WEBHOOK_SECRET");
  if (!configuredSecret) {
    console.error("[telegram-webhook] TELEGRAM_WEBHOOK_SECRET is not configured");
    return telegramJson({ error: "Webhook not configured" }, 500);
  }

  const url = new URL(req.url);
  const providedSecret =
    url.searchParams.get("secret") || req.headers.get("x-telegram-webhook-secret");
  if (!safeEqual(providedSecret, configuredSecret)) {
    return telegramJson({ error: "Unauthorized" }, 401);
  }

  let update: TelegramUpdate;
  try {
    update = (await req.json()) as TelegramUpdate;
  } catch (error) {
    console.warn("[telegram-webhook] invalid JSON payload", error);
    return telegramJson({ ok: true, ignored: true });
  }

  const message = update.message ?? update.edited_message;
  const chatType = message?.chat?.type;
  const chatId = message?.chat?.id;
  if (!message || !chatId) return telegramJson({ ok: true });

  const text = (message.text ?? "").trim();

  if (chatType === "group" || chatType === "supergroup") {
    if (/^\/id(@|\s|$)/i.test(text)) {
      await sendTelegramMessage(
        String(chatId),
        "FUN.RICH Security Bot only handles Telegram 2FA. Community Guard and Angel AI run on the separate FUN.RICH Community bot.",
      );
    }
    return telegramJson({ ok: true, ignored: "otp_bot_group_message" });
  }

  if (chatType !== "private") return telegramJson({ ok: true, ignored: "unsupported_chat_type" });

  if (/^\/id(@|\s|$)/i.test(text)) {
    await sendTelegramMessage(String(chatId), `User ID: <code>${chatId}</code>`);
    return telegramJson({ ok: true });
  }

  if (!isStartCommand(text)) {
    if (text && message.from?.is_bot !== true) {
      await sendTelegramMessage(
        String(chatId),
        "FUN.RICH Security Bot only handles Telegram 2FA. To connect Telegram, open FUN Profile -> Account Settings -> Telegram 2FA -> Connect Telegram.",
      );
    }
    return telegramJson({ ok: true, ignored: "non_start_private_message" });
  }

  const token = getStartToken(text);
  if (!token) {
    await sendTelegramMessage(
      String(chatId),
      "<b>FUN.RICH Security Bot</b>\n\nPlease do not type /start manually.\n\nTo connect Telegram 2FA:\n1. Open <b>FUN Profile</b>\n2. Go to <b>Account Settings -> Telegram 2FA</b>\n3. Click <b>Connect Telegram</b>\n4. Open the Telegram link generated by the app\n\nThe link expires after 15 minutes.",
    );
    return telegramJson({ ok: true });
  }

  const { adminClient } = getTelegramClients(req);
  const tokenHash = await sha256Hex(token);
  const nowIso = new Date().toISOString();

  const { data: linkToken, error: tokenError } = await adminClient
    .from("telegram_link_tokens")
    .select("id, user_id, expires_at, used_at")
    .eq("token_hash", tokenHash)
    .is("used_at", null)
    .gt("expires_at", nowIso)
    .maybeSingle();

  if (tokenError || !linkToken) {
    if (tokenError) console.warn("[telegram-webhook] link token lookup failed", tokenError);
    await sendTelegramMessage(
      String(chatId),
      "This FUN.RICH Telegram link expired. Please create a new link in Account Settings.",
    );
    return telegramJson({ ok: true });
  }

  const telegramUsername = message.from?.username ?? null;

  const { error: profileError } = await adminClient
    .from("profiles")
    .update({
      telegram_chat_id: String(chatId),
      telegram_username: telegramUsername,
      telegram_2fa_enabled: true,
      telegram_linked_at: nowIso,
    })
    .eq("id", linkToken.user_id);

  if (profileError) {
    console.error("[telegram-webhook] profile update failed", profileError);
    const errCode = (profileError as { code?: string }).code;
    await sendTelegramMessage(
      String(chatId),
      errCode === "23505"
        ? "This Telegram account is already linked to a different FUN.RICH user. Please disconnect it from the other account first."
        : "FUN.RICH could not connect this Telegram account. Please try again.",
    );
    return telegramJson({ ok: true });
  }

  await adminClient
    .from("telegram_link_tokens")
    .update({ used_at: nowIso })
    .eq("id", linkToken.id);

  await sendTelegramMessage(String(chatId), "Telegram 2FA is now enabled for your FUN.RICH account.");
  return telegramJson({ ok: true });
});
